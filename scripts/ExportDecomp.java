// 导出所有函数的 C 伪代码 + 反汇编
//@category MAX102

import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.*;
import ghidra.program.model.address.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.*;
import java.io.*;
import java.util.*;

public class ExportDecomp extends GhidraScript {

    @Override
    public void run() throws Exception {
        String outDir = System.getProperty("ghidra.out", "./temp/ghidra_out");
        new File(outDir).mkdirs();

        FunctionManager fm = currentProgram.getFunctionManager();
        DecompInterface dec = new DecompInterface();
        DecompileOptions opts = new DecompileOptions();
        dec.setOptions(opts);
        dec.openProgram(currentProgram);

        PrintWriter pwC = new PrintWriter(new FileWriter(new File(outDir, "decompiled_all.c")));
        PrintWriter pwIdx = new PrintWriter(new FileWriter(new File(outDir, "functions.txt")));
        PrintWriter pwAsm = new PrintWriter(new FileWriter(new File(outDir, "functions.asm")));

        pwC.println("/* MAX102 (WB32FQ95) Decompiled Functions */");
        pwC.println("/* Generated by Ghidra " + getGhidraVersion() + " */");
        pwC.println("");

        int nFunc = 0, nOk = 0, nFail = 0;
        List<Function> funcs = new ArrayList<>();
        for (Function f : fm.getFunctions(true)) funcs.add(f);
        println("total functions: " + funcs.size());

        for (Function f : funcs) {
            nFunc++;
            Address ep = f.getEntryPoint();
            String name = f.getName();
            pwIdx.println(String.format("0x%08X  %-40s  %d bytes  %s",
                    ep.getOffset(), name, f.getBody().getNumAddresses(),
                    f.getCalledFunctions(monitor).size() + " calls"));

            // 反汇编
            pwAsm.println("");
            pwAsm.println("; ============================================================");
            pwAsm.println("; FUNC " + name + " @ " + ep);
            pwAsm.println("; ============================================================");
            InstructionIterator it = currentProgram.getListing().getInstructions(f.getBody(), true);
            while (it.hasNext()) {
                Instruction ins = it.next();
                pwAsm.println(String.format("    %-8s  %s",
                        ins.getAddress().toString(),
                        ins.toString()));
            }

            // C 伪代码
            DecompileResults res = dec.decompileFunction(f, 60, monitor);
            pwC.println("");
            pwC.println("/* ============================================================");
            pwC.println(" * " + name + "  @ " + ep);
            pwC.println(" * ============================================================ */");
            if (res != null && res.decompileCompleted()) {
                nOk++;
                pwC.println(res.getDecompiledFunction().getC());
            } else {
                nFail++;
                pwC.println("// [decompile failed: " + (res == null ? "null" : res.getErrorMessage()) + "]");
            }
        }

        pwC.close(); pwIdx.close(); pwAsm.close();
        println("=== SUMMARY ===");
        println("functions total : " + nFunc);
        println("decompiled OK   : " + nOk);
        println("decompile FAIL  : " + nFail);
        println("output: " + outDir);
    }
}
